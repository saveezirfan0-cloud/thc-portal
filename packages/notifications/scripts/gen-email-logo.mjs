/**
 * The email logo — packages/notifications/src/assets/thc-mark-email.png and
 * its base64 twin, thc-mark-email.ts (ADR-0073).
 *
 * Every THC email carries the round mark in its header. Gmail blocks
 * `data:` URI images and a remote image is blocked until the reader clicks
 * "show images", so the mark travels with the message as an inline CID
 * attachment (`<img src="cid:thc-mark">`). The drain runs in Deno and reads
 * no files, so the bytes are ALSO written as a TS module it can import; a
 * test holds the two to each other.
 *
 * The mark is THC Light's: the glasses in the text colour #241D16 on a
 * round surface tile #F5F1EB with a hairline #EBE4DA ring, 96×96 so it is
 * sharp at the 36px it is drawn at on a 2–3× screen, and a few KB.
 *
 * Rasterised with sharp, resolved through the staff app's Next exactly as
 * `apps/staff/scripts/gen-push-badge.mjs` does (nothing declares it):
 *
 *   pnpm --filter @thc/notifications gen:logo
 */
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
const staff = createRequire(join(REPO, 'apps', 'staff', 'package.json'));
const sharp = createRequire(staff.resolve('next/package.json'))('sharp');

const SIZE = 96;
const MARK_H = 56; // the mark is tall: its height sets the size, as `.logo .logo-mark` does

const source = readFileSync(join(REPO, 'brand', 'thc-mark.svg'), 'utf8');
const viewBox = /viewBox="([^"]+)"/.exec(source)[1];
const [, , vbW, vbH] = viewBox.split(/\s+/).map(Number);
const paths = source.replace(/^[\s\S]*?<path/, '<path').replace(/<\/svg>\s*$/, '');
const markW = (MARK_H * vbW) / vbH;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <circle cx="48" cy="48" r="47.25" fill="#f5f1eb" stroke="#ebe4da" stroke-width="1.5"/>
  <svg x="${(SIZE - markW) / 2}" y="${(SIZE - MARK_H) / 2}" width="${markW}" height="${MARK_H}" viewBox="${viewBox}" fill="#241d16">${paths}</svg>
</svg>`;

const png = await sharp(Buffer.from(svg), { density: 288 })
  .resize(SIZE, SIZE)
  .png({ compressionLevel: 9, palette: true, colours: 64 })
  .toBuffer();

const assets = join(HERE, '..', 'src', 'assets');
mkdirSync(assets, { recursive: true });
writeFileSync(join(assets, 'thc-mark-email.png'), png);
writeFileSync(
  join(assets, 'thc-mark-email.ts'),
  `/**
 * GENERATED by packages/notifications/scripts/gen-email-logo.mjs from
 * brand/thc-mark.svg — do not edit; run \`pnpm --filter @thc/notifications gen:logo\`.
 * The same bytes as thc-mark-email.png beside it (held by email-html.test.ts),
 * as base64 so the Deno drain can import them without reading a file.
 */

export const THC_MARK_EMAIL_PNG_BASE64 =
  '${png.toString('base64')}';
`,
);
console.warn(`wrote src/assets/thc-mark-email.png (${png.length} bytes) and thc-mark-email.ts`);
